import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { resolve, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const revision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
if (!/^[0-9a-f]{40}$/.test(revision)) throw new Error('A full Git revision is required');
if (execFileSync('git', ['status', '--porcelain', '--untracked-files=no'], { cwd: root, encoding: 'utf8' }).trim()) {
  throw new Error('Prepare the release from a clean immutable checkout');
}
const shared = resolve(root, 'supabase/functions/_shared');
const files = [
  ...readdirSync(shared).filter(f => f.endsWith('.ts') && !f.endsWith('_test.ts') && f !== 'mcp-release-source.ts').map(f => resolve(shared, f)),
  resolve(root, 'supabase/functions/mcp-server/index.ts'),
  resolve(root, 'supabase/functions/mcp-oauth-metadata/index.ts'),
].sort();
const manifest = files.map(f => `${relative(root, f).replaceAll('\\', '/')} ${createHash('sha256').update(readFileSync(f)).digest('hex')}`).join('\n');
const release = { source_revision: revision, bundle_sha256: createHash('sha256').update(manifest).digest('hex') };
writeFileSync(resolve(shared, 'mcp-release-source.ts'), `// Generated by the manual deployment workflow.\nexport const MCP_RELEASE_SOURCE = ${JSON.stringify(release, null, 2)} as const;\n`);
console.log(JSON.stringify(release));
