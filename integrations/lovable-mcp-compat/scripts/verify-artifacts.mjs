import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(packageRoot, "../..");

const readJson = async (relativePath) =>
  JSON.parse(await readFile(path.resolve(repositoryRoot, relativePath), "utf8"));
const readText = (relativePath) =>
  readFile(path.resolve(repositoryRoot, relativePath), "utf8");

const [rootPackage, compatPackage, manifest, viteConfig, generatedFunction] = await Promise.all([
  readJson("package.json"),
  readJson("integrations/lovable-mcp-compat/package.json"),
  readJson(".lovable/mcp/manifest.json"),
  readText("vite.config.ts"),
  readText("supabase/functions/mcp/index.ts"),
]);

const rootDependencies = {
  ...rootPackage.dependencies,
  ...rootPackage.devDependencies,
  ...rootPackage.optionalDependencies,
};
const rootLovablePackages = Object.keys(rootDependencies).filter((name) =>
  name.includes("lovable")
);
if (rootLovablePackages.length > 0) {
  throw new Error(`Root package still installs Lovable packages: ${rootLovablePackages.join(", ")}`);
}
if (/lovable-tagger|@lovable\.dev\/mcp-js|mcpPlugin|componentTagger/.test(viteConfig)) {
  throw new Error("Canonical vite.config.ts still loads Lovable build plugins");
}

const sdkVersion = compatPackage.devDependencies?.["@lovable.dev/mcp-js"];
if (!sdkVersion || sdkVersion !== manifest.sdk_version) {
  throw new Error(`Manifest SDK ${manifest.sdk_version} does not match compatibility package ${sdkVersion}`);
}
if (manifest.path !== "/functions/v1/mcp") {
  throw new Error(`Unexpected legacy MCP path: ${manifest.path}`);
}
if (!generatedFunction.includes(`npm:@lovable.dev/mcp-js@${sdkVersion}`)) {
  throw new Error("Generated legacy function does not pin the compatibility SDK version");
}
if (!generatedFunction.startsWith("// AUTO-GENERATED by @lovable.dev/mcp-js")) {
  throw new Error("Generated legacy function lost its SDK ownership marker");
}

console.log(`Lovable MCP compatibility artifacts verified (SDK ${sdkVersion}).`);
