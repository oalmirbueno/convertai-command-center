import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { build } from "esbuild";
import { assertPortableImports, externalSpecifier } from "./portable-imports.mjs";

const BANNER = "// AUTO-GENERATED by @lovable.dev/mcp-js — do not edit. Regenerated by the Vite plugin.\n"
  + "// To take ownership, delete this banner line; the plugin then leaves the file alone.";

/**
 * SDK 0.23.0 externalizes C:\\... as npm:C:\\... before esbuild resolves it.
 * Keep its generated ownership format and runtime SDK, but bundle a relative
 * entry here. This adapter is used on every OS for identical checked-in bytes.
 * It never edits node_modules, removes artifacts, or loads private env files.
 */
export function portableMcpPlugin({ repositoryRoot, sdkVersion, publicEnv }) {
  return {
    name: "aceleriq-portable-mcp-compatibility",
    async buildStart() {
      const outputPath = path.resolve(repositoryRoot, "supabase/functions/mcp/index.ts");
      const [packageSource, existing] = await Promise.all([
        readFile(path.resolve(repositoryRoot, "package.json"), "utf8"),
        readFile(outputPath, "utf8").catch((error) => {
          if (error.code === "ENOENT") return null;
          throw error;
        }),
      ]);
      if (existing !== null && !existing.replace(/\r\n/g, "\n").startsWith(BANNER)) {
        throw new Error("Compatibility generator refuses to overwrite a function without its generated ownership marker");
      }
      const pkg = JSON.parse(packageSource);
      const versions = { ...pkg.peerDependencies, ...pkg.devDependencies, ...pkg.dependencies };
      const env = { ...publicEnv, MODE: "production", BASE_URL: "/", DEV: false, PROD: true, SSR: false };
      const result = await build({
        stdin: {
          contents: 'import mcp from "./src/lib/mcp/index.ts";\n'
            + 'import { createSupabaseHandler } from "@lovable.dev/mcp-js/stacks/supabase";\n'
            + 'Deno.serve(createSupabaseHandler(mcp, { functionName: "mcp" }));\n',
          resolveDir: repositoryRoot, sourcefile: "lovable-mcp-supabase-entry.ts", loader: "ts",
        },
        absWorkingDir: repositoryRoot, bundle: true, write: false, format: "esm",
        platform: "neutral", target: "esnext", logLevel: "silent",
        define: { "import.meta.env": JSON.stringify(env) },
        plugins: [{
          name: "portable-npm-imports",
          setup(builder) {
            builder.onResolve({ filter: /.*/ }, ({ path: specifier }) => {
              const external = externalSpecifier(specifier, versions, sdkVersion);
              return external === null ? null : { path: external, external: true };
            });
          },
        }],
      });
      const code = `${BANNER}\n// supabase function: mcp\n`
        + "// Bundled from src/lib/mcp/index.ts by the portable compatibility adapter.\n"
        + result.outputFiles[0].text;
      // Reject a broken bundle before replacing the last valid artifact.
      assertPortableImports(code);
      if (!code.includes(`npm:@lovable.dev/mcp-js@${sdkVersion}`)) {
        throw new Error("Compatibility bundle is missing its pinned runtime SDK");
      }
      if (existing !== code) await writeFile(outputPath, code, "utf8");
    },
  };
}
